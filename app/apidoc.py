def markdown(spec: dict) -> str:
    """То же описание текстом Markdown — тело ответа GET /api/v1."""
    out = [spec["info"]["description"], ""]
    for tag in spec["tags"]:
        out += [f"## {tag['name']}", "", tag["description"], ""]
        for path, methods in spec["paths"].items():
            for method, item in methods.items():
                if item["tags"] != [tag["name"]]:
                    continue
                params = item.get("parameters", [])
                out += [f"### {method.upper()} {path}" + ("?" + "&".join(p["name"] + "=" for p in params) if params else ""),
                        f"**{item['summary']}.** {item['description']}", ""]
                access = [f"Право: {item['x-rights']['text']}"]
                if item["x-key"] == "manage":           # обычный вход описан во вступлении
                    access.append(f"вход: {spec['x-key-kinds'][item['x-key']]}")
                access.append("платный — " + item["x-paid-when"] if item["x-paid"] else "бесплатный")
                out += ["; ".join(access) + ".", ""]
                if params:
                    out += ["Параметры:"] + [
                        f"- `{p['name']}`" + (" (обязателен)" if p.get("required") else "") + f" — {p['description']}"
                        for p in params] + [""]
                body = item.get("requestBody")
                if body and "application/octet-stream" in body["content"]:
                    out += [f"Тело запроса: {body['description'][0].lower()}{body['description'][1:]}.", ""]
                elif body:
                    media = body["content"]["application/json"]
                    ref = media["schema"].get("$ref", "").rsplit("/", 1)[-1]
                    model = spec["components"]["schemas"].get(ref, {})
                    need = set(model.get("required", []))
                    out += ["Тело запроса — JSON:"] + [
                        f"- `{name}`" + (" (обязательно)" if name in need else "") + f" — {prop['description']}"
                        for name, prop in model.get("properties", {}).items()]
                    out += ["", "```json", json.dumps(media["example"], ensure_ascii=False), "```", ""]
                good = next(iter(item["responses"]["200"]["content"].values()))
                fields = good["schema"].get("properties", {})
                if fields:
                    out += ["Ответ:"] + [f"- `{name}` — {prop['description']}" for name, prop in fields.items()]
                    out += ["", "```json", json.dumps(good["example"], ensure_ascii=False), "```", ""]
                refusals = [f"- {code}" + (f" «{r['detail']}»" if r["detail"] else "") + f" — {r['when']}"
                            for code, answer in item["responses"].items() if code not in ("200", "401", "422")
                            for r in answer["x-refusals"] if r["detail"] not in COMMON]
                if refusals:
                    out += ["Отказы:"] + refusals + [""]
                out += ["```bash", item["x-codeSamples"][0]["source"], "```", ""]
    return "\n".join(out).rstrip() + "\n"
