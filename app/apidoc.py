def _mode(text: str, personal: bool) -> str:
    """Оставляет куски своего режима: {{#personal}}…{{/personal}} или {{#corporate}}…{{/corporate}}."""
    keep, drop = ("personal", "corporate") if personal else ("corporate", "personal")
    text = re.sub(r"\{\{#%s\}\}.*?\{\{/%s\}\}" % (drop, drop), "", text, flags=re.S)
    return re.sub(r"\{\{[#/]%s\}\}" % keep, "", text)


# ---------- примеры запросов ----------

def _value(v: Any) -> str:
    return str(v).lower() if isinstance(v, bool) else str(v)


def _encoded(query: dict) -> str:
    return "?" + urlencode({k: _value(v) for k, v in query.items()}, quote_via=quote) if query else ""


def bash(op: Op, base: str, personal: bool) -> str:
    """Запрос для bash. Кириллицу в адресе кодирует сам curl (-G --data-urlencode); там, где тело
    запроса занято файлом или JSON, параметры стоят в адресе уже закодированными."""
    parts = ["curl -sS"] + ([] if personal or op.key == "none" else ['-H "Authorization: Bearer $KEY"'])
    url = base + op.path
    if op.binary:
        parts += [f'-T "./{op.query["name"]}"', f'"{url}{_encoded(op.query)}"']
    elif op.send is not None:
        body = json.dumps(op.send, ensure_ascii=False)
        assert "'" not in body, op.id
        parts += [f"-X {op.method}", '-H "Content-Type: application/json"', f"--data-binary '{body}'",
                  f'"{url}{_encoded(op.query)}"']
    else:
        parts += [f"-X {op.method}"] if op.method != "GET" else []
        parts += ["-G", f'"{url}"'] + [f'--data-urlencode "{k}={_value(v)}"' for k, v in op.query.items()] \
            if op.query else [f'"{url}"']
    return " ".join(parts + ([f'-o "{op.saves}"'] if op.saves else []))


def powershell(op: Op, base: str, personal: bool) -> str:
    """Запрос для Windows PowerShell 5.1 и новее: curl.exe, кириллица в адресе закодирована
    [uri]::EscapeDataString, тело JSON уходит из файла в UTF-8 — иначе PowerShell отдал бы его
    программе в кодировке консоли и без кавычек."""
    lines, query = [], []
    for k, v in op.query.items():
        if re.fullmatch(r"[\w.\-]*", _value(v), flags=re.A):
            query.append(f"{k}={_value(v)}")
        else:
            lines.append(f'${k} = [uri]::EscapeDataString("{_value(v)}")')
            query.append(f"{k}=${k}")
    parts = ["curl.exe -sS"] + ([] if personal or op.key == "none" else ['-H "Authorization: Bearer $env:KEY"'])
    if op.binary:
        parts.append(f'-T ".\\{op.query["name"]}"')
    elif op.send is not None:
        body = json.dumps(op.send, ensure_ascii=False)
        assert "'" not in body, op.id
        lines.append(f"[IO.File]::WriteAllText(\"$PWD\\body.json\", '{body}')")
        parts += [f"-X {op.method}", '-H "Content-Type: application/json"', '--data-binary "@body.json"']
    elif op.method != "GET":
        parts.append(f"-X {op.method}")
    parts.append(f'"{base}{op.path}{"?" + "&".join(query) if query else ""}"')
    return "\n".join(lines + [" ".join(parts + ([f'-o "{op.saves}"'] if op.saves else []))])


# ---------- сборка описания ----------

def _kind(value: Any) -> str:
    return {bool: "boolean", int: "integer", float: "number", str: "string", list: "array", dict: "object",
            type(None): "null"}[type(value)]


def _refusals(op: Op, personal: bool, has_input: bool) -> list[tuple[int, str, str]]:
    """Отказы метода: общие для его уровня доступа и свои."""
    out = []
    if op.key != "none" and not personal:
        out.append((401, NO_ENTRY, "нет заголовка авторизации, ключ не подходит, отозван или истёк"))
        out.append((429, TOO_MANY_PASSWORDS, "за 15 минут слишком много неверных паролей на этот логин или с вашего "
                                             "адреса: пароль не сверяется, пока не пройдёт 15 минут"))
        out.append((429, TOO_MANY_KEYS, "за 15 минут с вашего адреса пришло слишком много неверных ключей: ключ не "
                                        "проверяется, пока не пройдёт 15 минут"))
    if op.key == "manage" and not personal:
        out.append((403, PLAIN_KEY, "запрос пришёл с обычным ключом, а не с ключом «с управлением»"))
        if op.rights == ADMIN:
            out.append((403, op.denied or "это может только администратор сервиса",
                        "вошедший — не администратор сервиса"))
    out += list(op.errors)
    if op.body or op.send is not None:
        out.append((422, NOT_PARSED, "в теле не JSON или оно не в UTF-8"))
    if has_input:
        out.append((422, "не указан параметр ", "не хватает обязательного параметра или поля либо оно не того типа: в "
                                                "тексте — какое и что с ним не так"))
    return out


def _drop(node: Any, key: str) -> None:
    """Убирает из схемы служебные подписи FastAPI («Dir», «File»): описание параметра — в description."""
    if isinstance(node, dict):
        if isinstance(node.get(key), str):
            del node[key]
        for child in node.values():
            _drop(child, key)
    elif isinstance(node, list):
        for child in node:
            _drop(child, key)


def build(app, base: str, personal: bool, max_gb: str, version: str) -> dict:
    """Описание внешнего API в виде OpenAPI 3.1. Параметры и тела запросов — из маршрутов
    приложения, слова — отсюда. base — адрес сервиса, personal — личный ли режим."""
    # в личном режиме человек один и входа нет: раздел «Управление» ему не описывают
    ops = {(o.method, o.path): o for o in _ops(max_gb) if not (personal and o.tag == MANAGE)}
    routes = [r for r in app.routes if isinstance(r, APIRoute) and any((m, r.path) in ops for m in r.methods)]
    spec = get_openapi(title="Подьячий — API", version=version or "0", routes=routes)
    _drop(spec, "title")
    schemas = spec.get("components", {}).get("schemas", {})
    paths: dict[str, dict] = {}
    for op in ops.values():                                     # порядок — как в описании, по разделам
        made = spec["paths"][op.path][op.method.lower()]
        params = made.get("parameters", [])
        for p in params:
            p["description"] = _mode(op.params[p["name"]], personal)
            if p["name"] in op.query:
                p["example"] = op.query[p["name"]]
        item = {"operationId": op.id, "tags": [op.tag], "summary": op.summary, "description": _mode(op.text, personal),
                "x-rights": {"level": op.rights, "text": op.rights_text or RIGHTS[op.rights]},
                "x-key": "none" if personal else op.key, "x-paid": bool(op.paid)}
        if op.paid:
            item["x-paid-when"] = op.paid
        if personal or op.key == "none":
            item["security"] = []
        if params:
            item["parameters"] = params
        if op.binary:
            item["requestBody"] = {"required": True, "description": op.binary, "content": {
                "application/octet-stream": {"schema": {"type": "string", "format": "binary"}}}}
        elif "requestBody" in made:
            body = made["requestBody"]
            media = body["content"]["application/json"]
            model = schemas[media["schema"]["$ref"].rsplit("/", 1)[1]] if "$ref" in media["schema"] else None
            if model:
                for name, prop in model["properties"].items():
                    prop["description"] = op.body[name]
            if op.send is not None:
                media["example"] = op.send
            item["requestBody"] = body
        shape = {"type": "string"} if op.media != "application/json" else {"type": "object", "properties": {
            name: {"type": _kind(op.answer[name]), "description": _mode(text, personal)}
            for name, text in op.fields.items()}}
        item["responses"] = {"200": {"description": "Успех", "content": {op.media: {"schema": shape, "example": op.answer}}}}
        by_code: dict[int, list[tuple[str, str]]] = {}
        for code, text, when in _refusals(op, personal, bool(params) or "requestBody" in item):
            by_code.setdefault(code, []).append((text, when))
        for code in sorted(by_code):
            item["responses"][str(code)] = {
                "description": "; ".join(dict.fromkeys(when for _, when in by_code[code])),
                "x-refusals": [{"detail": text, "when": when} for text, when in by_code[code]],
                "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Refusal"}}}}
        item["x-codeSamples"] = [{"lang": "bash", "label": "bash", "source": bash(op, base, personal)},
                                 {"lang": "powershell", "label": "PowerShell", "source": powershell(op, base, personal)}]
        paths.setdefault(op.path, {})[op.method.lower()] = item
    used = json.dumps(paths)
    spec = {
        "openapi": spec["openapi"],
        "info": {"title": "Подьячий — API", "version": version or "0", "description": _intro(base, personal, max_gb)},
        "servers": [{"url": base}],
        "tags": [{"name": name, "description": text} for name, text in TAGS.items()
                 if any(o.tag == name for o in ops.values())],
        "paths": paths,
        "components": {
            "schemas": {**{name: s for name, s in schemas.items() if f"schemas/{name}\"" in used},
                        "Refusal": {"type": "object", "description": "Отказ: код ответа и текст по-русски.",
                                    "properties": {"detail": {"type": "string", "description": "что не так"}}}},
            "securitySchemes": {} if personal else {
                "key": {"type": "http", "scheme": "bearer", "description":
                        "Ключ доступа `stg_…`: человек выпускает его себе в окне «Ключи доступа» на странице сервиса."},
                "password": {"type": "http", "scheme": "basic", "description":
                             "Логин и пароль учётной записи, заведённой в самом сервисе (не доменной)."}}},
        "x-rights-levels": RIGHTS,
        "x-key-kinds": KEYS,
    }
    if not personal:
        spec["security"] = [{"key": []}, {"password": []}]
    return copy.deepcopy(spec)


